import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const code=await readFile(new URL('../gesture/input/FingerClick.js',import.meta.url),'utf8');
const {FingerClick}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const cfg={clickArmMs:180,clickMinMs:70,clickMaxMs:430,clickCooldownMs:280,grabHoldMs:430};
const point={straight:true,bent:false,fist:false},fist={straight:false,bent:true,fist:true};
const click=new FingerClick(cfg);
click.update(point,0);click.update(point,200);
assert.equal(click.update(fist,250).confirm,false);
assert.equal(click.update(point,400).confirm,true,'click only on reopening');
assert.equal(click.update(point,450).confirm,false,'no repeated click');
const grab=new FingerClick(cfg);grab.update(point,0);grab.update(point,200);grab.update(fist,250);
assert.equal(grab.update(fist,700).mode,'grab');
assert.equal(grab.update(point,750).confirm,false,'release after grab must not click');
const tremor=new FingerClick(cfg);tremor.update(point,0);tremor.update(point,200);tremor.update(fist,220);
assert.equal(tremor.update(point,250).confirm,false,'reject brief noise');
const loss=new FingerClick(cfg);loss.update(point,0);loss.update(point,200);loss.update(fist,230);loss.reset();
assert.equal(loss.update(point,400).confirm,false,'tracking loss cancels click');
const initialFist=new FingerClick(cfg);initialFist.update(fist,0);
assert.equal(initialFist.update(fist,450).mode,'grab');
console.log('Passed: curl/reopen click, held fist, noise, tracking loss, initial grab.');

const gradual=new FingerClick(cfg);
const partial={straight:false,bent:false,fist:false};
gradual.update(point,0);gradual.update(point,200);
assert.equal(gradual.phase,'armed');
gradual.update(partial,230);gradual.update(partial,260);
assert.equal(gradual.phase,'armed','half-bent transition must preserve readiness');
gradual.update(fist,290);
assert.equal(gradual.phase,'bend');
assert.equal(gradual.update(partial,330).confirm,false);
assert.equal(gradual.update(partial,370).confirm,false);
assert.equal(gradual.update(point,400).confirm,true,'gradual curl and reopen must click');
const held=new FingerClick(cfg);
held.update(point,0);held.update(point,200);held.update(partial,250);held.update(fist,300);
assert.equal(held.update(fist,750).mode,'grab','holding still enters grab');
assert.equal(held.update(point,800).confirm,false,'releasing a held fist must not click');
console.log('Passed: gradual bending/reopening through intermediate angles, retained grab timeout.');
