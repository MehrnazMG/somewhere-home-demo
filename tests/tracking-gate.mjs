import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const src=await readFile(new URL('../gesture/input/TrackingGate.js',import.meta.url),'utf8');
const {TrackingGate}=await import('data:text/javascript;base64,'+Buffer.from(src).toString('base64'));
const cfg={reacquireAfterMs:140,maxPalmJump:.22,reacquireRadius:.07,reacquireFrames:3};
const gate=new TrackingGate(cfg);
const hand=(x,y)=>Array.from({length:21},()=>({x,y,z:0}));
assert.equal(gate.accept(hand(.85,.9),0),false);
assert.equal(gate.accept(hand(.84,.89),33),false);
assert.equal(gate.accept(hand(.85,.9),66),true);
assert.equal(gate.accept(hand(.1,.1),99),false,'opposite-corner outlier rejected');
assert.equal(gate.accept(hand(.84,.9),132),true,'normal tracking resumes without moving to the outlier');
const tip=hand(.84,.9);tip[8]={x:.1,y:.1};
assert.equal(gate.accept(tip,165),false,'isolated fingertip jump rejected');
assert.equal(gate.accept(hand(.83,.89),198),true);
assert.equal(gate.accept(hand(.4,.4),500),false,'re-entry must stabilize');
assert.equal(gate.accept(hand(.41,.4),533),false);
assert.equal(gate.accept(hand(.4,.4),566),true);
assert.equal(gate.accept(hand(1.1,.8),599),false,'off-camera palm rejected');
assert.equal(gate.accept(hand(NaN,.8),632),false);
console.log('Passed: stable entry, palm/fingertip corner jumps, recovery, tracking gap, clipped/invalid hand.');
